#!/usr/bin/env node
/*
 * Regenerate the direct-file effect bundle from the nine redistributed OGG masters.
 *
 * Browsers commonly reject fetch() for file:// media. Encoding the exact delivered bytes here lets the
 * runtime decode the same masters through Web Audio in direct-file and HTTP launches without maintaining
 * a second set of synthesized sounds.
 */
import fs from 'node:fs';
import path from 'node:path';
import process from 'node:process';
import { fileURLToPath } from 'node:url';

const TOOL_DIRECTORY = path.dirname(fileURLToPath(import.meta.url));
const PROJECT_ROOT = path.resolve(TOOL_DIRECTORY, '..');
const OUTPUT_PATH = path.join(
  PROJECT_ROOT,
  'src/audio/Neon_Autopilot_V23_HighSpeed_DroneHeat.effect-assets.js'
);
const RELEASE_GENERATION = '23-ipad-road-residency-253';
const MODULE_VERSION = 'V23-effect-assets-1';
const DATA_URL_PREFIX = 'data:audio/ogg;base64,';
const ASSET_FILES = Object.freeze({
  impact: 'impactMetal_003.ogg',
  pickup: 'powerUp3.ogg',
  jump: 'phaseJump3.ogg',
  route: 'threeTone1.ogg',
  accelerate: 'phaserUp3.ogg',
  brake: 'phaserDown2.ogg',
  gameOver: 'lowDown.ogg',
  button: 'click3.ogg',
  toggle: 'switch2.ogg'
});

function wrapStringLiteral(value) {
  const chunks = value.match(/.{1,120}/g) || [''];
  return chunks
    .map((chunk, index) => (index === 0 ? `'${chunk}'` : `        '${chunk}'`))
    .join(' +\n');
}

/** Render a deterministic browser module whose payload is byte-for-byte derived from the OGG masters. */
function renderModule(dataUrls) {
  const dataUrlSource = Object.entries(dataUrls)
    .map(([key, dataUrl]) => `    ${key}: ${wrapStringLiteral(dataUrl)}`)
    .join(',\n');

  return `/*
 * V23 exact-byte inline effect masters for direct-file audio parity.
 *
 * These data URLs contain the unchanged bytes of the nine redistributed OGG files. Runtime decodes them
 * through the same Web Audio graph used for HTTP-loaded assets; this module is transport, not a remix.
 *
 * Generated by tools/generate-effect-audio-inline.mjs; do not hand-edit encoded audio data.
 */
(() => {
  'use strict';

  const dataUrls = Object.freeze({
${dataUrlSource}
  });

  window.NeonV23EffectAssets = Object.freeze({
    version: '${MODULE_VERSION}',
    releaseGeneration: '${RELEASE_GENERATION}',
    dataUrls
  });
})();
`;
}

const dataUrls = {};
for (const [key, filename] of Object.entries(ASSET_FILES)) {
  const sourcePath = path.join(PROJECT_ROOT, 'assets/audio', filename);
  const sourceBytes = fs.readFileSync(sourcePath);
  if (sourceBytes.subarray(0, 4).toString('ascii') !== 'OggS') {
    throw new Error(`Effect master is not an OGG stream: ${sourcePath}`);
  }
  dataUrls[key] = `${DATA_URL_PREFIX}${sourceBytes.toString('base64')}`;
}

fs.writeFileSync(OUTPUT_PATH, renderModule(dataUrls));
process.stderr.write(`Wrote ${OUTPUT_PATH}\n`);
